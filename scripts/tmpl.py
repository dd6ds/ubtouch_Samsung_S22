#!/usr/bin/env python3
"""Turn real boot.img / vendor_boot.img headers into templates/<dev>/header.env.

    tmpl.py <unpack_bootimg.py> <boot.img> <vendor_boot.img> <outdir>

Writes <outdir>/header.env (sourced by scripts/lib.sh) and <outdir>/bootconfig.txt.
Only header values are taken over; kernel, ramdisks and dtb are always ours.
"""
import os, shlex, subprocess, sys, tempfile

unpack, boot, vboot, outdir = sys.argv[1:5]


def mkargs(img):
    with tempfile.TemporaryDirectory() as d:
        out = subprocess.run([sys.executable, unpack, "--boot_img", img, "--out", d,
                              "--format=mkbootimg"], check=True, capture_output=True, text=True).stdout
        args = shlex.split(out)
        res, files = {}, {}
        i = 0
        while i < len(args):
            k = args[i].lstrip("-")
            v = args[i + 1] if i + 1 < len(args) else ""
            res.setdefault(k, v)
            i += 2
        bc = res.get("vendor_bootconfig")
        if bc and os.path.exists(bc):
            files["bootconfig"] = open(bc).read()
        return res, files


b, _ = mkargs(boot)
v, vf = mkargs(vboot)
env = {
    "deviceinfo_bootimg_os_version": b.get("os_version", ""),
    "deviceinfo_bootimg_os_patch_level": b.get("os_patch_level", ""),
    "deviceinfo_bootimg_pagesize": str(int(v.get("pagesize", "2048"), 0)),
    "deviceinfo_bootimg_base": v.get("base", ""),
    "deviceinfo_bootimg_kernel_offset": v.get("kernel_offset", ""),
    "deviceinfo_bootimg_ramdisk_offset": v.get("ramdisk_offset", ""),
    "deviceinfo_bootimg_tags_offset": v.get("tags_offset", ""),
    "deviceinfo_bootimg_dtb_offset": v.get("dtb_offset", ""),
    "template_boot_cmdline": b.get("cmdline", ""),
    "template_vendor_cmdline": v.get("vendor_cmdline", ""),
}
os.makedirs(outdir, exist_ok=True)
with open(os.path.join(outdir, "header.env"), "w") as f:
    f.write("# generated by scripts/pull-templates.sh from the phone's own boot images\n")
    for k, val in env.items():
        if val != "":
            f.write(f"{k}={shlex.quote(val)}\n")
    if "bootconfig" in vf:
        f.write("template_bootconfig_file=\"$TEMPLATE_DIR/bootconfig.txt\"\n")
if "bootconfig" in vf:
    with open(os.path.join(outdir, "bootconfig.txt"), "w") as f:
        f.write(vf["bootconfig"])
for k, val in env.items():
    print(f"  {k} = {val}")
